/**
 * `exportJSON()` 写进文件、`importJSON()` 校验的**数据版本号**。
 *
 * 加一个新键（或改一个字段的含义）时 +1；只是新增图形类型不用动它 ——
 * 数据文件是**类型无关**的，`type` 就是个字符串，41 种内置类型和自定义类型一视同仁。
 * 导入时版本高于本值直接抛错（见 `serialize.ts` 的 `parseSketchData`），
 * 所以别为了「顺手加点东西」跳过这一步：旧版本静默丢掉看不懂的字段，最难查。
 *
 * 版本史：
 * - 1：`{ app, version, shapes }`
 * - 2：外壳加 `style`（全局基础样式整份带走）。迁移分支在 `importJSON`：
 *      v1 老文件没有 `style`，**不动**导入方的全局样式（不能拿现在的出厂默认
 *      去覆盖 —— 那正是「老文件导回来颜色变了」的来源）。
 * - 3：`style` 加第 18 个键 `haloWidth`（文字描边宽度）。v2 老文件缺这一个键，
 *      由 `pickGlobalStyle` 补上出厂值即可，**不需要迁移分支**；而反方向（旧引擎
 *      读 v3 新文件）会明确报错「请升级 mapbox-sketch」，不会静默按自己的老默认值
 *      渲染出错误的描边粗细 —— 这正是这个版本号要防的事。
 * - 4：每条图形加可选的 `data`（**类型私有数据**，图片标注用它装图片本体与自然尺寸）。
 *      加它**必须**升版本号的原因不是「多了一个键」，而是它的含义反过来：
 *      v3 引擎读 v4 文件会**整条照收**（`readShapeData` 只挑自己认识的键，`data` 被丢掉），
 *      于是图片标注导进来是**一张空图/占位框** —— 静默丢内容最该被挡住。
 *      v3 老文件缺 `data`，缺省即「没有私有数据」，**不需要迁移分支**。
 * - 5：`style` 加第 19 个键 `lineType`（线型：实线 / 虚线 / 点线 / 点划线）。
 *      纯**新增**键，v4 老文件缺这一个键由 `pickGlobalStyle` 补上出厂值即可，
 *      **不需要迁移分支**；反方向（旧引擎读 v5 文件）会明确报错「请升级 mapbox-sketch」，
 *      不会静默按自己的老默认值渲染出实线 —— 这正是这个版本号要防的事。
 *      ★ 之后再有类型往这个口袋里装自己的东西（如文字标注的旋转角 `rot`）**不必**再动
 *      版本号：外壳没变，只是这个自由字典里多了一个键；反方向的兼容性也已经有人兜着 ——
 *      旧引擎不认识的**类型**是整条跳过并告警，不会静默丢内容（见 `sketch.ts` 的导入）——
 *      这正是 v4 当初要防的事。
 * - 6：`style` 加第 20、21 个键 `bgColor` / `bgRadius`（富文本标注的**整条标注背景**
 *      —— 一整块矩形，铺在全部字下面，出厂纯白，见 `Style.bgColor`）。
 *      与 v5 同款：纯**新增**键，v5 老文件缺这两个键由 `pickGlobalStyle` 补上出厂值即可，
 *      **不需要迁移分支**；反方向（旧引擎读 v6 文件）会明确报错「请升级 mapbox-sketch」，
 *      不会静默忽略新键、按「不垫底」渲染 —— 那看起来就像「背景丢了」。
 */
