/* =====================================================================
 * export-prefs.ts —— 绘制项目的 dpi / 图片格式偏好。
 *
 * 导出面板桥与组件都从这里读取同一份状态，避免各存一份后预览和实际导出不一致。
 *
 * ★ 注意「共用」的边界：这只是 UI 偏好的复用，不是持久化 —— 刷新页面就回到
 *   默认值。要记住用户上次的选择得另写 localStorage，目前没有这个需求。
 *
 * `use-sketch.ts`（绘制桥）从这里拿值再 re-export；组件不另造一份状态。
 * ===================================================================== */
import { ref } from 'vue';

/** 导出分辨率（dpi） */
export const exportDpi = ref(300);

/**
 * dpi 下拉的**候选列表** —— 两个页面共用的不只是当前值，选项表也是同一份：
 * 首页面板与专题页都按它渲染 `el-select`，改这里两边同时变。
 */
export const DPI_LIST = [96, 150, 200, 300, 400, 500, 600];

/** 导出图片格式（默认 JPEG：专题图输出多为影像底图，JPEG 体积小得多） */
export const exportFormat = ref<'png' | 'jpeg'>('jpeg');
